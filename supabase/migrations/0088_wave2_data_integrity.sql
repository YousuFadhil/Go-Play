create or replace function public.advance_match_participation_revision()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_match_id uuid;
  v_community_id uuid;
  v_status text;
  v_end_at timestamptz;
  v_revision bigint;
  v_actor uuid;
begin
  v_match_id := case when tg_op = 'DELETE' then old.match_id else new.match_id end;

  select m.community_id, m.status, m.end_at
  into v_community_id, v_status, v_end_at
  from public.matches m
  where m.id = v_match_id;

  if not found then
    if tg_op = 'DELETE' then return old; end if;
    return new;
  end if;

  insert into public.match_participation_state (
    match_id,
    lineup_revision
  )
  values (v_match_id, 1)
  on conflict (match_id) do update
    set lineup_revision =
      public.match_participation_state.lineup_revision + 1
  returning lineup_revision into v_revision;

  v_actor := auth.uid();

  if (v_status = 'completed' or v_end_at <= now())
     and v_actor is not null
     and public.has_active_community_role(
       v_community_id,
       v_actor,
       'admin'
     )
  then
    update public.match_participation_state
    set confirmed_revision = v_revision,
        confirmed_at = now(),
        confirmed_by = v_actor
    where match_id = v_match_id;
  end if;

  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

revoke execute on function public.advance_match_participation_revision()
  from public, anon, authenticated;


create trigger match_team_assignments_advance_participation_revision
after insert or update or delete on public.match_team_assignments
for each row execute function public.advance_match_participation_revision();


create or replace function public.confirm_match_participation(
  p_match_id uuid
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_match public.matches%rowtype;
begin
  if auth.uid() is null then
    raise exception 'NOT_AUTHENTICATED';
  end if;

  if not public.is_current_user_active() then
    raise exception 'ACCOUNT_SUSPENDED';
  end if;

  select *
  into v_match
  from public.matches
  where id = p_match_id
  for update;

  if not found then
    raise exception 'MATCH_NOT_FOUND';
  end if;

  if not exists (
    select 1
    from public.communities c
    where c.id = v_match.community_id
      and c.is_active
  ) then
    raise exception 'COMMUNITY_INACTIVE';
  end if;

  if not public.has_active_community_role(
    v_match.community_id,
    auth.uid(),
    'admin'
  ) then
    raise exception 'NOT_AUTHORIZED';
  end if;

  if v_match.status <> 'completed'
     and v_match.end_at > now()
  then
    raise exception 'MATCH_NOT_COMPLETED';
  end if;

  if not exists (
    select 1
    from public.match_team_assignments a
    where a.match_id = p_match_id
  ) then
    raise exception 'LINEUP_REQUIRED';
  end if;

  insert into public.match_participation_state (
    match_id,
    lineup_revision
  )
  values (p_match_id, 1)
  on conflict (match_id) do nothing;

  update public.match_participation_state
  set confirmed_revision = lineup_revision,
      confirmed_at = now(),
      confirmed_by = auth.uid()
  where match_id = p_match_id;
end;
$$;

comment on function public.confirm_match_participation(uuid) is
  'Wave 2 organizer confirmation that the current completed lineup is the factual participation record. Does not alter lineup, result, ratings or statistics.';

revoke execute on function public.confirm_match_participation(uuid)
  from public, anon;
grant execute on function public.confirm_match_participation(uuid)
  to authenticated, service_role;


